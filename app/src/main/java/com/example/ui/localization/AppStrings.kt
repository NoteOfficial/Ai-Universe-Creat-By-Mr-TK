fun UiStrings.categoryName(cat: AiCategory): String =
  when (cat) {
    AiCategory.GENERAL -> catGeneral
    AiCategory.CODING -> catCoding
    AiCategory.WEBSITE_BUILDER -> catWebsiteBuilder
    AiCategory.IMAGE -> catImage
    AiCategory.VIDEO -> catVideo
    AiCategory.AUDIO -> catAudio
    AiCategory.RESEARCH -> catResearch
    AiCategory.PRODUCTIVITY -> catProductivity
    AiCategory.OTHER -> catOther
  }

fun UiStrings.pricingName(pricing: PricingType): String =
  when (pricing) {
    PricingType.COMPLETELY_FREE -> allFree
    PricingType.FREE_AND_PAID -> freePlusPaid
    PricingType.PAID -> paidAi
  }

fun UiStrings.compatName(status: CompatibilityStatus): String =
  when (status) {
    CompatibilityStatus.IN_APP_WEBVIEW -> inAppWebView
    CompatibilityStatus.EXTERNAL_TAB_RECOMMENDED -> externalTabRec
    CompatibilityStatus.COMPATIBILITY_UNKNOWN -> compatUnknown
  }

fun UiStrings.sortName(opt: SortOption): String =
  when (opt) {
    SortOption.DEFAULT -> sortDefault
    SortOption.NAME_ASC -> sortNameAsc
    SortOption.FAVORITES_FIRST -> sortFavoritesFirst
    SortOption.CATEGORY -> sortCategory
  }

fun UiStrings.themeModeName(mode: ThemeMode): String =
  when (mode) {
    ThemeMode.SYSTEM -> themeSystem
    ThemeMode.LIGHT -> themeLight
    ThemeMode.DARK -> themeDark
  }

fun UiStrings.paletteName(palette: ColorPaletteTheme): String =
  when (palette) {
    ColorPaletteTheme.COSMIC_VIOLET -> paletteCosmicViolet
    ColorPaletteTheme.OCEAN_AURORA -> paletteOceanAurora
    ColorPaletteTheme.SUNSET_CORAL -> paletteSunsetCoral
    ColorPaletteTheme.EMERALD_CYBER -> paletteEmeraldCyber
    ColorPaletteTheme.ROYAL_AMETHYST -> paletteRoyalAmethyst
  }

fun UiStrings.fontScaleName(opt: FontScaleOption): String =
  when (opt) {
    FontScaleOption.SMALL -> sizeCompact
    FontScaleOption.NORMAL -> sizeNormal
    FontScaleOption.LARGE -> sizeLarge
  }

fun UiStrings.iconSizeName(opt: IconSizeOption): String =
  when (opt) {
    IconSizeOption.COMPACT -> sizeCompact
    IconSizeOption.NORMAL -> sizeNormal
    IconSizeOption.LARGE -> sizeLarge
  }

